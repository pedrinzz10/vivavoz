def nome_arquivo(texto):
    sem_acento = unicodedata.normalize('NFKD', texto.lower()).encode('ascii', 'ignore').decode()
    base = re.sub(r'[^a-z0-9]+', '-', sem_acento).strip('-')
    return base or 'feature'


def gerar():
    features = [f[0] for _, _, fs in EPICOS for f in fs]
    faltando = [f for f in features if f not in CT]
    assert not faltando, f'Features sem casos de teste: {faltando}'

    with open(os.path.join(PASTA, 'backlog.csv'), 'w', encoding='utf-8-sig', newline='') as arquivo:
        saida = csv.writer(arquivo)
        saida.writerow(['ID', 'Work Item Type', 'Title 1', 'Title 2', 'Title 3', 'Description', 'Acceptance Criteria',
                        'Priority', 'Tags'])
        for epico, descricao, features_epico in EPICOS:
            saida.writerow(['', 'Epic', epico, '', '', descricao, '', 1, 'VozViva'])
            for feature, desc, criterios, pbis in features_epico:
                saida.writerow(['', 'Feature', '', feature, '', desc, lista(criterios), 1, 'VozViva'])
                for titulo, historia, crit in pbis:
                    saida.writerow(['', 'Product Backlog Item', '', '', titulo, historia, lista(crit), 2, 'VozViva'])

    pasta_ct = os.path.join(PASTA, 'casos-de-teste')
    os.makedirs(pasta_ct, exist_ok=True)
    total = 0
    for feature, casos in CT.items():
        with open(os.path.join(pasta_ct, nome_arquivo(feature) + '.csv'), 'w', encoding='utf-8-sig', newline='') as arquivo:
            saida = csv.writer(arquivo)
            saida.writerow(['ID', 'Work Item Type', 'Title', 'Test Step', 'Step Action', 'Step Expected', 'Priority',
                            'Description', 'Tags'])
            for titulo, tipo, objetivo, preparacao, entradas, esperado, passos in casos:
                sumario = (f'<b>Objetivo:</b> {objetivo}<br><b>Preparação:</b> {preparacao}<br>'
                           f'<b>Entradas:</b> {entradas}<br><b>Saída esperada:</b> {esperado}')
                for numero, (acao, resultado) in enumerate(passos, start=1):
                    if numero == 1:
                        saida.writerow(['', 'Test Case', f'[{tipo}] {titulo}', numero, acao, resultado, 2, sumario,
                                        f'VozViva; {feature}; {tipo}'])
                    else:
                        saida.writerow(['', '', '', numero, acao, resultado, '', '', ''])
                total += 1
    print(f'{len(EPICOS)} epics, {len(features)} features, '
          f'{sum(len(f[3]) for _, _, fs in EPICOS for f in fs)} PBIs, {total} casos de teste')


if __name__ == '__main__':
    gerar()
